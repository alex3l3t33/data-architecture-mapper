import type { ArchitectureComponent, ArchitectureGraph, SubprojectConfig, ValidationFinding } from "../model/types";
import { deterministicId } from "../model/ids";
import { stableJson } from "../utils/objects";
import { MermaidGenerator, type EnvironmentMermaidDiagram } from "./mermaid";
import { DATABASE_TYPES, databaseWorkloads, type RelatedDatabaseWorkload } from "../graph/database-workloads";
import { INFRASTRUCTURE_TYPES, infrastructureCharacteristics, infrastructureParentPaths, infrastructureTypeLabel } from "../graph/infrastructure";

export const GENERATED_MARKER = "<!-- Generated by Data Architecture Mapper. Do not edit this file manually. -->";

export interface GeneratedDocument {
  path: string;
  content: string;
}

export class MarkdownGenerator {
  constructor(private readonly mermaid = new MermaidGenerator()) {}

  generate(
    projectName: string,
    graph: ArchitectureGraph,
    findings: ValidationFinding[],
    subprojects: readonly SubprojectConfig[] = [],
    environmentOrder: readonly string[] = []
  ): GeneratedDocument[] {
    const diagrams = this.mermaid.generatePartitions(graph);
    const overview = [
      GENERATED_MARKER,
      "",
      `# ${escapeMarkdown(projectName)} — Data Architecture`,
      "",
      "> Static configuration analysis shows architectural reachability, not confirmed runtime behavior.",
      "",
      "## Summary",
      "",
      `- Components: ${graph.components.length}`,
      `- Relationships: ${graph.relationships.length}`,
      `- Connectors: ${count(graph, "kafka-connector")}`,
      `- Topics: ${count(graph, "kafka-topic")}`,
      `- Applications: ${count(graph, "application")}`,
      `- Findings: ${findings.length}`,
      "",
      "## Architecture",
      "",
      ...diagrams.flatMap((diagram) => [
        `### ${escapeMarkdown(diagram.name)}`,
        "",
        "```mermaid",
        diagram.mermaid,
        "```",
        ""
      ]),
      "## Source diagnostics",
      "",
      graph.diagnostics.length ? table(["Severity", "Source", "Message"], graph.diagnostics.map((diagnostic) => [
        diagnostic.severity,
        sourceLink(diagnostic.path),
        diagnostic.message
      ])) : "No parser diagnostics.",
      ""
    ].join("\n");

    const connectors = graph.components.filter((component) => component.type === "kafka-connector");
    const infrastructure = graph.components.filter((component) => INFRASTRUCTURE_TYPES.has(component.type));
    const workloads = databaseWorkloads(graph);
    const subprojectNames = subprojects.length ? new Map(subprojects.map(({ id, name }) => [id, name])) : undefined;
    const connectorDiagrams = this.mermaid.generateConnectorDiagrams(
      graph, new Set(connectors.map((connector) => connector.id)), "LR", environmentOrder
    );
    return [
      { path: "Architecture Overview.md", content: overview },
      { path: "Connectors.md", content: inventory("Connector inventory", connectors) },
      ...connectorArchitectureDocuments(connectorDiagrams),
      { path: "Topics.md", content: inventory("Kafka topic inventory", graph.components.filter((component) => component.type === "kafka-topic")) },
      { path: "Applications.md", content: inventory("Application inventory", graph.components.filter((component) => component.type === "application"), subprojectNames) },
      { path: "Databases.md", content: inventory("Database inventory", graph.components.filter((component) => DATABASE_TYPES.has(component.type)), undefined, workloads) },
      ...(infrastructure.length ? [{ path: "Infrastructure.md", content: infrastructureInventory(graph, infrastructure, workloads) }] : []),
      { path: "Validation.md", content: findingsDocument(findings) },
      { path: "Unresolved Dependencies.md", content: inventory("Unresolved dependencies", graph.components.filter((component) => component.unresolved === true)) },
      { path: "architecture.json", content: `${stableJson({ ...graph, generatedAt: undefined })}\n` }
    ];
  }
}

function connectorArchitectureDocuments(diagrams: readonly EnvironmentMermaidDiagram[]): GeneratedDocument[] {
  const filenames = connectorDiagramFilenames(diagrams.map((diagram) => diagram.environment));
  const documents = diagrams.map((diagram) => {
    const filename = filenames.get(diagram.environment)!;
    const label = escapeMarkdown(diagram.environment.replace(/[\r\n]+/g, " "));
    return {
      path: `${filename}.md`,
      link: `- [[${filename}]] · ${diagram.connectorCount} ${diagram.connectorCount === 1 ? "connector" : "connectors"}`,
      content: [
        GENERATED_MARKER, "", `# Connector architecture — ${label}`, "",
        "```mermaid", diagram.mermaid, "```", ""
      ].join("\n")
    };
  });
  const index: GeneratedDocument = {
    path: "Connector Architecture.md",
    content: [
      GENERATED_MARKER, "", "# Connector architecture", "",
      ...(documents.length ? documents.map((document) => document.link) : ["No Kafka Connect connectors were discovered."]), ""
    ].join("\n")
  };
  return [index, ...documents.map(({ path, content }) => ({ path, content }))];
}

function connectorDiagramFilenames(environments: string[]): Map<string, string> {
  const filenames = new Map<string, string>();
  const used = new Set<string>();
  for (const environment of [...environments].sort()) {
    const normalized = environment.normalize("NFKC").replace(/[^\p{L}\p{N} _-]+/gu, "-").trim();
    const safe = Array.from(normalized).slice(0, 48).join("").replace(/^[ -]+|[ -]+$/g, "") || "Environment";
    const hashed = `${safe}-${deterministicId("env", environment)}`;
    const suffix = safe === environment && !used.has(safe.toLowerCase()) ? safe : hashed;
    let unique = suffix;
    for (let number = 2; used.has(unique.toLowerCase()); number += 1) unique = `${suffix}-${number}`;
    used.add(unique.toLowerCase());
    filenames.set(environment, `Connector Architecture - ${unique}`);
  }
  return filenames;
}

function inventory(
  title: string,
  components: ArchitectureComponent[],
  subprojectNames?: ReadonlyMap<string, string>,
  workloads?: ReadonlyMap<string, RelatedDatabaseWorkload[]>
): string {
  const headers = ["Name", "Type", ...(subprojectNames ? ["Subproject"] : []), "Environment", "Technology", "Cluster",
    ...(workloads ? ["Related workloads"] : []), "Sources"];
  const rows = components.sort((a, b) => a.id.localeCompare(b.id)).map((component) => [
    component.name,
    component.type,
    ...(subprojectNames ? [subprojectLabel(component, subprojectNames)] : []),
    component.environment,
    component.technology ?? "",
    component.kafkaClusterId?.split(":").pop() ?? "",
    ...(workloads ? [workloadNames(workloads.get(component.id))] : []),
    component.evidence.map((evidence) => sourceLink(evidence.path)).join("<br>")
  ]);
  return [GENERATED_MARKER, "", `# ${title}`, "", rows.length ? table(headers, rows) : "No components discovered.", ""].join("\n");
}

function infrastructureInventory(graph: ArchitectureGraph, components: ArchitectureComponent[], workloads: ReadonlyMap<string, RelatedDatabaseWorkload[]>): string {
  const paths = infrastructureParentPaths(graph);
  const rows = components.map((component) => [
    escapeMarkdown(component.name),
    infrastructureTypeLabel(component.type),
    escapeMarkdown(component.environment),
    escapeMarkdown(component.technology ?? ""),
    escapeMarkdown(paths.get(component.id) ?? ""),
    infrastructureCharacteristics(component).map(([field, value]) =>
      escapeMarkdown(`${field}: ${typeof value === "string" ? value : stableJson(value, 0)}`)
    ).join("<br>"),
    workloadNames(workloads.get(component.id)),
    [...new Set(component.evidence.map((evidence) => sourceLink(evidence.path)))].join("<br>")
  ]);
  return [GENERATED_MARKER, "", "# Infrastructure inventory", "",
    table(["Name", "Type", "Environment", "Platform", "Cluster / host", "Characteristics", "Related workloads", "Sources"], rows), ""].join("\n");
}

function workloadNames(workloads: RelatedDatabaseWorkload[] = []): string {
  return workloads.map(({ name, evidencePaths }) => {
    const sources = evidencePaths.map(sourceLink).join(", ");
    return escapeMarkdown(name) + (sources ? ` (${sources})` : "");
  }).join("<br>");
}

function subprojectLabel(component: ArchitectureComponent, names: ReadonlyMap<string, string>): string {
  return component.subprojectIds?.map((id) => names.get(id) ?? id).join(", ") || "Parent project";
}

function findingsDocument(findings: ValidationFinding[]): string {
  const rows = findings.map((finding) => [
    finding.severity,
    finding.ruleId,
    finding.confidence,
    finding.explanation,
    finding.recommendation,
    finding.evidence.map((evidence) => sourceLink(evidence.path)).join("<br>")
  ]);
  return [GENERATED_MARKER, "", "# Validation findings", "", rows.length
    ? table(["Severity", "Rule", "Confidence", "Explanation", "Recommended action", "Sources"], rows)
    : "No findings.", ""].join("\n");
}

function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.map(cell).join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map((value) => cell(String(value))).join(" | ")} |`)
  ].join("\n");
}

function cell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function sourceLink(path: string): string {
  return `[[${path.replace(/\.md$/i, "")}|${path.split("/").pop()}]]`;
}

function count(graph: ArchitectureGraph, type: string): number {
  return graph.components.filter((component) => component.type === type).length;
}

function escapeMarkdown(value: string): string {
  return value.replace(/[\\`*_{}[\]<>#]/g, "\\$&");
}
